import logging
import os
import re
from typing import Optional
from github.PullRequest import PullRequest

logger = logging.getLogger("pr_summary.updater")

START_TAG = "<!-- PR-SUMMARY-WRITER:START -->"
END_TAG = "<!-- PR-SUMMARY-WRITER:END -->"

# Also match legacy/alternate tag variations
START_TAG_REGEX = re.compile(
    r"<!--\s*(?:PR-SUMMARY-WRITER|PR-SUMMARIZER|AUTOGENERATED_PR_SUMMARY)[:_]START\s*-->",
    re.IGNORECASE,
)
END_TAG_REGEX = re.compile(
    r"<!--\s*(?:PR-SUMMARY-WRITER|PR-SUMMARIZER|AUTOGENERATED_PR_SUMMARY)[:_]END\s*-->",
    re.IGNORECASE,
)
STICKY_COMMENT_TAG = "<!-- PR-SUMMARY-WRITER:STICKY-COMMENT -->"


def update_pr_description_text(existing_body: Optional[str], summary_markdown: str) -> str:
    """
    Updates or inserts the summary block inside the PR body while strictly preserving
    all human notes, reasoning, and pre-existing text.
    """
    raw_body = (existing_body or "").strip()
    formatted_block = f"{START_TAG}\n{summary_markdown}\n{END_TAG}"

    start_match = START_TAG_REGEX.search(raw_body)
    end_match = END_TAG_REGEX.search(raw_body)

    if start_match and end_match and start_match.start() < end_match.end():
        # Replace only the content between start and end markers
        before = raw_body[:start_match.start()].rstrip()
        after = raw_body[end_match.end():].lstrip()

        parts = []
        if before:
            parts.append(before)
        parts.append(formatted_block)
        if after:
            parts.append(after)

        return "\n\n".join(parts)

    # Markers not present in existing body
    if not raw_body:
        template = (
            "## Developer Notes & Rationale\n"
            "<!-- Add your architectural intent, reasoning, or manual context here -->\n\n"
            f"{formatted_block}"
        )
        return template

    return f"{raw_body}\n\n{formatted_block}"


class PRUpdater:
    def __init__(self, pr: PullRequest):
        self.pr = pr

    def update_description(self, summary_markdown: str) -> bool:
        """Updates the PR body description in-place."""
        try:
            current_body = self.pr.body or ""
            new_body = update_pr_description_text(current_body, summary_markdown)
            if new_body != current_body:
                self.pr.edit(body=new_body)
                logger.info(f"Successfully updated PR #{self.pr.number} description in-place.")
                return True
            else:
                logger.info(f"PR #{self.pr.number} description is already up-to-date.")
                return False
        except Exception as e:
            logger.error(f"Failed to update PR description: {e}")
            raise

    def update_sticky_comment(self, summary_markdown: str) -> None:
        """Finds or creates a sticky pinned comment on the PR containing the summary."""
        comment_body = f"{STICKY_COMMENT_TAG}\n{summary_markdown}"

        try:
            for comment in self.pr.get_issue_comments():
                if STICKY_COMMENT_TAG in (comment.body or ""):
                    comment.edit(body=comment_body)
                    logger.info(f"Updated existing sticky summary comment #{comment.id} on PR #{self.pr.number}.")
                    return

            self.pr.create_issue_comment(comment_body)
            logger.info(f"Created new sticky summary comment on PR #{self.pr.number}.")
        except Exception as e:
            logger.error(f"Failed to update sticky comment: {e}")
            raise

    def write_step_summary(self, summary_markdown: str) -> None:
        """Writes the generated summary to $GITHUB_STEP_SUMMARY for CI visibility."""
        step_summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
        if step_summary_path and os.path.isfile(step_summary_path):
            try:
                with open(step_summary_path, "a", encoding="utf-8") as f:
                    f.write("\n\n" + summary_markdown + "\n")
                logger.info("Wrote summary to GITHUB_STEP_SUMMARY.")
            except Exception as e:
                logger.debug(f"Could not write to GITHUB_STEP_SUMMARY: {e}")
